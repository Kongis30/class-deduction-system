CREATE TABLE IF NOT EXISTS lesson_record_revoke_audit (
    id BIGINT NOT NULL,
    lesson_record_id BIGINT NOT NULL,
    occurrence_id BIGINT NOT NULL,
    package_id BIGINT NULL,
    result_status VARCHAR(64) NOT NULL,
    deducted_units INT NOT NULL DEFAULT 0,
    reason VARCHAR(1000) NOT NULL,
    revoked_by_user_id BIGINT NOT NULL,
    revoked_at DATETIME NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    is_deleted TINYINT NOT NULL DEFAULT 0,
    deleted_at DATETIME NULL,
    deleted_by BIGINT NULL,
    version INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_lesson_revoke_audit_record (lesson_record_id, revoked_at),
    KEY idx_lesson_revoke_audit_occurrence (occurrence_id, revoked_at)
);

CREATE TABLE IF NOT EXISTS lesson_record_schedule_effect (
    id BIGINT NOT NULL,
    source_lesson_record_id BIGINT NOT NULL,
    affected_occurrence_id BIGINT NOT NULL,
    before_planning_status VARCHAR(32) NOT NULL,
    before_planned_start_at DATETIME NOT NULL,
    before_planned_end_at DATETIME NOT NULL,
    before_planned_units INT NOT NULL,
    after_planning_status VARCHAR(32) NOT NULL,
    after_planned_start_at DATETIME NOT NULL,
    after_planned_end_at DATETIME NOT NULL,
    after_planned_units INT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    is_deleted TINYINT NOT NULL DEFAULT 0,
    deleted_at DATETIME NULL,
    deleted_by BIGINT NULL,
    version INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_lesson_schedule_effect (source_lesson_record_id, affected_occurrence_id),
    KEY idx_lesson_schedule_effect_affected (affected_occurrence_id)
);

CREATE TABLE IF NOT EXISTS lesson_record_makeup_effect (
    id BIGINT NOT NULL,
    source_lesson_record_id BIGINT NOT NULL,
    makeup_occurrence_id BIGINT NOT NULL,
    generated_version INT NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    is_deleted TINYINT NOT NULL DEFAULT 0,
    deleted_at DATETIME NULL,
    deleted_by BIGINT NULL,
    version INT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_lesson_makeup_effect_record (source_lesson_record_id),
    UNIQUE KEY uk_lesson_makeup_effect_occurrence (makeup_occurrence_id)
);
